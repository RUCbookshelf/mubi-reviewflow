  function node(tag, text, attrs = {}) {
    const n = document.createElement(tag);
    if (text != null) n.textContent = T(text);
    for (const [key, value] of Object.entries(attrs)) n.setAttribute(key, value);
    return n;
  }
  function raw(tag, text, attrs = {}) {
    const n = node(tag, null, {translate:'no', ...attrs});
    n.textContent = String(text ?? '—'); return n;
  }
  function size(bytes) {
    if (bytes == null) return '—';
    const units = ['B', 'KB', 'MB', 'GB', 'TB']; let index = 0;
    while (bytes >= 1024 && index < units.length - 1) { bytes /= 1024; index++; }
    return new Intl.NumberFormat(RFLang.get(), {maximumFractionDigits:1}).format(bytes) + ' ' + units[index];
  }
  function button(label, action, primary = false) {
    const n = node('button', label, {type:'button', class:'btn '+(primary?'b-inc':'b-out')});
    n.disabled = busy; n.addEventListener('click', action); return n;
  }
  async function act(action, success) {
    if (busy) return;
    busy = true; message = ''; render();
    try { await action(); message = success; await load(); }
    catch (e) { message = storageError(e); }
    finally { busy = false; render(); }
  }
  function item(label, value) {
    const line = node('div', null, {class:'local-storage-item'});
    line.append(node('dt', label), raw('dd', value)); return line;
  }
  function render() {
    panel.hidden = runtimeMode !== 'desktop';
    title.hidden = panel.hidden;
    if (panel.hidden) return;
    title.textContent = T('数据存放位置');
    panel.replaceChildren();
    if (!state) {
      panel.append(node('p', message || '正在加载…', {class:'hint', role:'status'}));
      if (message) panel.append(button('重试', load));
      return;
    }
    panel.append(node('p', 'PDF、文献、筛选、编码和轨迹数据保存在同一目录。', {class:'hint'}));
    const facts = node('dl', null, {class:'local-storage-facts'});
    facts.append(item('当前目录', state.current_path), item('已用空间', size(state.bytes)), item('可用空间', size(state.free_bytes)));
    panel.append(facts);
    if (state.last_error) {
      panel.append(node('p', '迁移失败，当前仍使用原目录。', {class:'hint',role:'alert'}), node('p', storageError(state.last_error), {class:'hint local-storage-detail'}));
    }
    if (state.pending_path) {
      const pending = node('dl', null, {class:'local-storage-facts'});
      pending.append(item('待迁移目录', state.pending_path)); panel.append(pending);
      const restart = node('div', null, {class:'local-storage-restart',role:'status'});
      restart.append(node('strong', '重启应用后生效'), node('p', '迁移将在下次启动时执行。请先退出应用；Windows 用户可重启电脑后再打开。'));
      panel.append(restart);
      panel.append(node('p', '迁移完成前继续使用当前目录。', {class:'hint'}));
      panel.append(button('取消迁移', () => act(() => api('/api/local-storage/migration/cancel',{method:'POST'}),'已取消迁移。')));
    } else if (state.enabled !== false) {
      const label = node('label', '新数据目录', {class:'lbl',for:'localStorageDestination'});
      const input = node('input', null, {id:'localStorageDestination',class:'input',type:'text',spellcheck:'false',translate:'no'});
      input.value = destination; input.placeholder = T('请输入新的绝对路径，例如 D:\\ReviewFlowData。');
      input.disabled = busy; input.addEventListener('input', () => {destination = input.value;});
      const controls = node('div', null, {class:'local-storage-controls'}); controls.append(input);
      if (state.can_browse) controls.append(button('选择文件夹', () => act(async () => {
        const result = await api('/api/local-storage/browse',{method:'POST'});
        if (result.path) destination = result.path;
      },'')));
      controls.append(button('迁移到新目录', () => {
        if (!destination.trim()) {message = '请输入新的绝对路径，例如 D:\\ReviewFlowData。'; render(); return;}
        if (confirm(T('将全部本机研究数据迁移到所选目录？')+'\n'+destination))
          act(() => api('/api/local-storage/migration',{method:'POST',body:{destination:destination.trim()}}),'已安排迁移，下次启动时执行。');
      }, true));
      panel.append(label, controls, node('p','请选择空文件夹，不能选择当前目录或其内部文件夹。',{class:'hint'}));
      panel.append(node('p','此设置对本机所有账号和任务生效。',{class:'hint'}));
    }
    if (state.backup_path) {
      const backup = node('dl', null, {class:'local-storage-facts'}); backup.append(item('旧数据目录',state.backup_path)); panel.append(backup);
      panel.append(node('p','原目录保留为备份。确认 PDF 和研究数据正常后，可清理旧数据以释放磁盘空间。',{class:'hint'}));
      panel.append(button('清理旧数据', () => {
        if (confirm(T('永久删除旧目录中的研究数据？此操作无法撤销，请先确认新目录的数据完整。')))
          act(() => api('/api/local-storage/cleanup',{method:'POST',body:{confirm:true}}),'旧数据已清理。');
      }));
    }
    if (busy || message) panel.append(node('p',busy?'执行中，请稍候。':message,{class:'hint',role:'status'}));
  }
  async function load() {
    if (!S.user || runtimeMode !== 'desktop') {panel.hidden = title.hidden = true; return;}
    const turn = ++ticket; const user = S.user.username;
    try {
      const result = await api('/api/local-storage');
      if (turn !== ticket || S.user?.username !== user) return;
      state = result;
    } catch (e) {
      if (turn !== ticket) return;
      message = '无法读取存储设置，请重试。';
    }
    render();
  }
